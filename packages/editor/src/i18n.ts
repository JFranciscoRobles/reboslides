/** The names of shapes, units, sizes, themes and layouts in a language: the engine's own in Spanish. */
export function namesFor(language: 'en' | 'es') {
  const en = language === 'en';
  return {
    shape: (kind: ShapeKind) => (en ? SHAPE_NAMES_EN[kind] : SHAPE_NAMES[kind]),
    unit: (unit: Unit) => (en ? UNIT_NAMES_EN[unit] : UNIT_NAMES[unit]),
    preset: (preset: SizePreset) => (en ? (PRESET_NAMES_EN[preset.id] ?? preset.name) : preset.name),
    theme: (theme: Theme) => (en ? (THEME_NAMES_EN[theme.id] ?? theme.name) : theme.name),
    layout: (layout: LayoutKind) => (en ? LAYOUT_NAMES_EN[layout] : LAYOUT_NAMES[layout]),
  };
}

export type Names = ReturnType<typeof namesFor>;
