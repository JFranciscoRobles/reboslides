export const LOCALES: Record<string, Strings> = { en: EN, es: ES };

/** The language of a locale the studio speaks: 'en' or 'es', Spanish unless it is English. */
export const languageOf = (locale: string | undefined): 'en' | 'es' => (locale?.toLowerCase().startsWith('en') ? 'en' : 'es');

export function stringsFor(locale: string | undefined): Strings {
  return LOCALES[languageOf(locale)];
}

/** A text with its `{name}`s filled in. */
export const say = (text: string, values: Record<string, string | number>): string => text.replace(/\{(\w+)\}/g, (_m, k: string) => String(values[k] ?? ''));

